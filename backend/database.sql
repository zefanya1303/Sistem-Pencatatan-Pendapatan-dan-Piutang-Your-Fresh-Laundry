create table if not exists public.transactions (
  id_transaksi bigint generated by default as identity primary key,
  id_customer bigint not null references public.customers(id_customer) on delete restrict,
  id_jenis_cucian bigint references public.jenis_cucian(id_jenis_cucian) on delete restrict,
  tanggal_transaksi date not null default current_date,
  jam_transaksi time not null default localtime,
  created_at timestamptz not null default now(),
  jumlah integer,
  berat_kg numeric(8,2) check (berat_kg > 0),
  menggunakan_vanish boolean not null default false,
  biaya_vanish_per_kg integer not null default 3000 check (biaya_vanish_per_kg >= 0),
  tambahan_vanish integer not null default 0 check (tambahan_vanish >= 0),
  total_pendapatan integer not null check (total_pendapatan > 0),
  status_pembayaran text not null default 'Belum Lunas'
    check (status_pembayaran in ('Lunas', 'Belum Lunas')),
  status_cucian text not null default 'Belum Selesai'
    check (status_cucian in ('Belum Selesai', 'Selesai - Belum Diambil', 'Sudah Diambil')),
  tanggal_selesai date not null,
  jenis_deterjen text not null default 'Deterjen Cair Laundry',
  jenis_pewangi text not null,
  keterangan text not null default '',
  -- Legacy snapshots remain for old transaction history; new rows use the FK above.
  jenis_cucian text,
  jenis_laundry text,
  harga_per_kg integer,
  nama_barang text,
  jumlah_satuan integer,
  harga_per_satuan integer
);

