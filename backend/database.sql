create or replace function public.check_payment_limit()
returns trigger
language plpgsql
as $$
declare
  transaction_total integer;
  already_paid integer;
begin
  select total_pendapatan into transaction_total
  from public.transactions
  where id_transaksi = new.id_transaksi
  for update;

  select coalesce(sum(jumlah_pembayaran), 0) into already_paid
  from public.payments
  where id_transaksi = new.id_transaksi
    and (tg_op = 'INSERT' or id_payment <> new.id_payment);

  if already_paid + new.jumlah_pembayaran > transaction_total then
    raise exception 'Jumlah pembayaran melebihi sisa tagihan.';
  end if;

  return new;
end;
$$;

create or replace function public.refresh_transaction_payment_status()
returns trigger
language plpgsql
as $$
declare
  target_transaction bigint;
begin
  target_transaction := coalesce(new.id_transaksi, old.id_transaksi);

  update public.transactions
  set status_pembayaran = case
    when coalesce((
      select sum(jumlah_pembayaran)
      from public.payments
      where id_transaksi = target_transaction
    ), 0) >= total_pendapatan then 'Lunas'
    else 'Belum Lunas'
  end
  where id_transaksi = target_transaction;

  return null;
end;
$$;

create or replace function public.prevent_unpaid_laundry_pickup()
returns trigger
language plpgsql
as $$
declare
  amount_paid integer;
begin
  if new.status_cucian = 'Sudah Diambil'
     and old.status_cucian is distinct from new.status_cucian then
    select coalesce(sum(jumlah_pembayaran), 0) into amount_paid
    from public.payments
    where id_transaksi = new.id_transaksi;

    if amount_paid < new.total_pendapatan then
      raise exception 'Cucian belum dapat diambil karena pembayaran belum lunas.';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists transactions_prevent_unpaid_pickup on public.transactions;
create trigger transactions_prevent_unpaid_pickup
before update of status_cucian on public.transactions
for each row execute function public.prevent_unpaid_laundry_pickup();

drop trigger if exists payments_check_limit on public.payments;
create trigger payments_check_limit
before insert or update on public.payments
for each row execute function public.check_payment_limit();

drop trigger if exists payments_refresh_status on public.payments;
create trigger payments_refresh_status
after insert or update or delete on public.payments
for each row execute function public.refresh_transaction_payment_status();

