create or replace function public.validate_transaction_total()
returns trigger
language plpgsql
as $$
declare
  laundry_type public.jenis_cucian%rowtype;
  expected_vanish integer;
  expected_total integer;
begin
  select * into laundry_type
  from public.jenis_cucian
  where id_jenis_cucian = new.id_jenis_cucian;

  if not found then
    raise exception 'Jenis cucian tidak ditemukan.';
  end if;

  if laundry_type.satuan = 'kg' then
    if new.berat_kg is null or new.berat_kg <= 0 or new.jumlah is not null then
      raise exception 'Transaksi pakaian biasa harus menggunakan berat dalam kg.';
    end if;

    expected_vanish := case
      when new.menggunakan_vanish then round(new.berat_kg * new.biaya_vanish_per_kg)::integer
      else 0
    end;
    expected_total := round(new.berat_kg * laundry_type.harga)::integer + expected_vanish;
    if new.tambahan_vanish <> expected_vanish then
      raise exception 'Perhitungan tambahan Vanish tidak sesuai.';
    end if;
  else
    if new.jumlah is null or new.jumlah <= 0 or new.berat_kg is not null
       or new.menggunakan_vanish or new.tambahan_vanish <> 0 then
      raise exception 'Transaksi barang khusus harus menggunakan jumlah satuan.';
    end if;
    expected_total := new.jumlah * laundry_type.harga;
  end if;

  if new.total_pendapatan <> expected_total then
    raise exception 'Total transaksi tidak sesuai harga dan jumlah cucian.';
  end if;

  return new;
end;
$$;

drop trigger if exists transactions_validate_total on public.transactions;
drop trigger if exists transactions_validate_total_insert on public.transactions;
create trigger transactions_validate_total_insert
before insert on public.transactions
for each row execute function public.validate_transaction_total();
drop trigger if exists transactions_validate_total_update on public.transactions;
create trigger transactions_validate_total_update
before update of id_jenis_cucian, jumlah, berat_kg, total_pendapatan,
  menggunakan_vanish, biaya_vanish_per_kg, tambahan_vanish
on public.transactions
for each row execute function public.validate_transaction_total();

